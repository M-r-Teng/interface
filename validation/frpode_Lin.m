%ode45计算F-sl曲线 Lin本构主动约束
clear;
global lam2 press
Ef=33.2*10^3;tf=12.7;
lam2=1/(Ef*tf);
press=12;%MPa,侧向约束应力大小
dotnum=150; sinmax=8;%可变，单位mm。对此的分步大小只会影响F-L曲线的疏密，但不影响每个F的精度。
geo=1.15; %等比数列的比例
s0in(dotnum)=sinmax;
for i=dotnum-1:-1:1 %分num步
s0in(i)=s0in(i+1)/geo;
end
for i=1:dotnum %分num步
[sl(i),F(i)]=frps0con(s0in(i));
end
plot(sl,F,'-o')
xlabel('sl/mm');
ylabel('F/kN');
sl=sl';F=F';

function [sl,F]= frps0con(sinput)
       global s0 
    s0=sinput;
    L=200;%/mm 
   
[xmesh,sx] = ode45(@(t,y) odefcn(t,y),[0 L],[s0; 0]);

    leny=size(sx,1); 
    sx=sx(:,1);
    for i=1:leny %也可用向量运算
        tao(i)=taoLinp(sx(i));  
    end
    F=trapz(xmesh,tao)/1000;%kN
    sl=sx(leny);
end

function dydt = odefcn(t,y)
global lam2
  dydt = zeros(2,1);
  dydt(1) = y(2);
  dydt(2) = lam2*taoLinp(y(1));
end

